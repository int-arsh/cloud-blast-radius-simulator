"""Pydantic models for risk findings, severity, scoring, and decision status."""

from enum import StrEnum
from typing import Any

from pydantic import BaseModel, Field

from blast_radius.models.graph import ConfidenceLevel
from blast_radius.models.plan import NormalizedAction


class RiskSeverity(StrEnum):
    """Severity classification of an individual risk finding."""

    INFO = "info"
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"
    CRITICAL = "critical"


class DecisionStatus(StrEnum):
    """Overall evaluation decision status for automated CI/CD gating."""

    PASS = "pass"
    REVIEW_REQUIRED = "review_required"
    BLOCKED = "blocked"
    ANALYSIS_INCOMPLETE = "analysis_incomplete"


class RiskFinding(BaseModel):
    """Evidence-backed individual risk finding generated by a deterministic safety rule."""

    id: str = Field(..., description="Unique finding identifier")
    rule_id: str = Field(..., description="Stable rule identifier e.g. RULE-001")
    rule_name: str = Field(..., description="Human-readable rule name")
    severity: RiskSeverity = Field(..., description="Severity level")
    resource_address: str = Field(..., description="Canonical address of affected resource")
    proposed_action: NormalizedAction = Field(..., description="Proposed lifecycle action")
    evidence: list[str] = Field(..., description="Verified evidence backing this finding")
    reasoning: str = Field(..., description="Logical connection from evidence to risk conclusion")
    confidence: ConfidenceLevel = Field(
        ConfidenceLevel.VERIFIED, description="Confidence level of this finding"
    )
    limitations: str = Field(
        ..., description="Documented limitations, assumptions, or boundary conditions"
    )
    remediation: str = Field(..., description="Recommended remediation or safe alternative")
    missing_information: str | None = Field(
        None, description="Any missing information that could alter the conclusion"
    )
    source_location: str = Field(
        "configuration (exact source line number unavailable in plan JSON)",
        description="Source provenance reference",
    )


class RiskScoreBreakdown(BaseModel):
    """Explainable factors comprising the final deterministic risk score."""

    base_score: float = Field(..., description="Raw sum of severity finding weights")
    blast_radius_multiplier: float = Field(
        1.0, description="Multiplier derived from downstream impacted resource count"
    )
    confidence_factor: float = Field(1.0, description="Scaling factor based on evidence confidence")
    final_score: float = Field(
        ..., description="Final bounded score from 0.0 (safe) to 100.0 (extreme risk)"
    )
    formula: str = Field(..., description="Human-readable explanation of score computation formula")


class RiskEvaluationResult(BaseModel):
    """Complete evaluation result produced by the risk and scoring engine."""

    decision_status: DecisionStatus = Field(..., description="Overall gate decision")
    decision_reason: str = Field(..., description="Primary reason justifying the decision status")
    risk_score: float = Field(..., description="Deterministic risk score (0.0 to 100.0)")
    score_breakdown: RiskScoreBreakdown = Field(..., description="Detailed score breakdown")
    severity_counts: dict[str, int] = Field(
        default_factory=dict, description="Finding count per severity level"
    )
    findings: list[RiskFinding] = Field(
        default_factory=list, description="Ordered list of all detected risk findings"
    )
    metadata: dict[str, Any] = Field(default_factory=dict, description="Evaluation metadata")
